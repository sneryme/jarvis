let d = "";
process.stdin.on("data", c => d += c);
process.stdin.on("end", () => {
  let p = "";
  try { p = (JSON.parse(d).prompt || "").toLowerCase(); } catch (e) {}
  const money = /(потратил|потратила|купил|купила|заплатил|заплатила|расход|трат|сколько.*(ушло|потрат)|\d+\s*(₽|руб|р\b|к\b|тыс))/;
  const plans = /(на недел|на месяц|на завтра|на сегодня|завтра|сегодня|задач|мероприят|событи|план|встреч|день рожд|брифинг|календар|что у меня|дела)/;
  if (money.test(p)) {
    console.log("ВАЖНО: это сообщение о расходах. Загрузи навык rashody и действуй строго по нему (запись в Google Таблицу «Расходы» или отчёт).");
  } else if (plans.test(p)) {
    console.log("ВАЖНО: это вопрос о планах. Загрузи навык obzor и выполни его полностью: заново опроси ВСЕ календари (с BIRTHDAY) и ВСЕ списки Google Tasks, даже если данные уже были в разговоре. Выведи ответ строго в формате навыка. Если спросили про одну категорию — покажи её первой, остальное кратко ниже.");
  }
});